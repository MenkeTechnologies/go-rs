//! Go's `unicode` case mapping and the three character classes `strings`
//! consults (`IsLetter`, `IsDigit`, `IsSpace`), ported from unicode/letter.go
//! and unicode/graphic.go with the tables transcribed from unicode/tables.go.
//!
//! Go maps case rune by rune with the *simple* case mappings
//! (`unicode.ToUpper('ß')` is `'ß'`, `ToUpper('ᾳ')` is `'ᾼ'`), where Rust's
//! `char::to_uppercase` applies the full, string-lengthening ones — so the
//! `strings` builtins go through these instead.

/// `unicode.UpperCase`, `LowerCase` and `TitleCase`: indexes into a case
/// range's deltas.
pub(crate) const UPPER_CASE: usize = 0;
pub(crate) const LOWER_CASE: usize = 1;
pub(crate) const TITLE_CASE: usize = 2;

/// `unicode.UpperLower`: a delta marking an alternating Upper/Lower sequence.
const UPPER_LOWER: i32 = 0x10FFFF + 1;

/// `unicode.To`: map `r` to `case` (`UPPER_CASE` / `LOWER_CASE` /
/// `TITLE_CASE`). A rune with no mapping maps to itself.
pub(crate) fn to(case: usize, r: u32) -> u32 {
    match lookup_case_range(r) {
        Some(cr) => convert_case(case, r, cr),
        None => r,
    }
}

/// `unicode.ToUpper`.
pub(crate) fn to_upper(r: u32) -> u32 {
    if r < 0x80 {
        return if (u32::from(b'a')..=u32::from(b'z')).contains(&r) {
            r - 32
        } else {
            r
        };
    }
    to(UPPER_CASE, r)
}

/// `unicode.ToLower`.
pub(crate) fn to_lower(r: u32) -> u32 {
    if r < 0x80 {
        return if (u32::from(b'A')..=u32::from(b'Z')).contains(&r) {
            r + 32
        } else {
            r
        };
    }
    to(LOWER_CASE, r)
}

/// `unicode.ToTitle`.
pub(crate) fn to_title(r: u32) -> u32 {
    if r < 0x80 {
        // title case is upper case for ASCII
        return if (u32::from(b'a')..=u32::from(b'z')).contains(&r) {
            r - 32
        } else {
            r
        };
    }
    to(TITLE_CASE, r)
}

/// `unicode.lookupCaseRange`: the case range holding `r`, by binary search.
fn lookup_case_range(r: u32) -> Option<&'static (u32, u32, [i32; 3])> {
    let i = CASE_RANGES.partition_point(|cr| cr.1 < r);
    CASE_RANGES.get(i).filter(|cr| cr.0 <= r)
}

/// `unicode.convertCase`.
fn convert_case(case: usize, r: u32, cr: &(u32, u32, [i32; 3])) -> u32 {
    let delta = cr.2[case];
    if delta > 0x10FFFF {
        // In an Upper-Lower sequence, which always starts with an UpperCase
        // letter, the characters at even offsets from the beginning are upper
        // case and the ones at odd offsets lower: clear or set the low bit of
        // the offset. UpperCase and TitleCase are even, LowerCase is odd.
        debug_assert_eq!(delta, UPPER_LOWER);
        return cr.0 + (((r - cr.0) & !1) | (case as u32 & 1));
    }
    (r as i64 + i64::from(delta)) as u32
}

/// `unicode.SimpleFold`: the next rune after `r` in its case-folding orbit,
/// wrapping to the smallest.
pub(crate) fn simple_fold(r: u32) -> u32 {
    if r > 0x10FFFF {
        return r;
    }
    if let Some(&f) = ASCII_FOLD.get(r as usize) {
        return u32::from(f);
    }
    // Consult caseOrbit table for special cases.
    let i = CASE_ORBIT.partition_point(|p| u32::from(p.0) < r);
    if let Some(p) = CASE_ORBIT.get(i).filter(|p| u32::from(p.0) == r) {
        return u32::from(p.1);
    }
    // No folding specified. This is a one- or two-element equivalence class
    // containing rune and ToLower(rune) and ToUpper(rune) if they are
    // different from rune.
    if let Some(cr) = lookup_case_range(r) {
        let l = convert_case(LOWER_CASE, r, cr);
        if l != r {
            return l;
        }
        return convert_case(UPPER_CASE, r, cr);
    }
    r
}

/// `unicode.Is` over one of the range tables below: `r` is in a range and on
/// its stride.
fn is_in(table: &[(u32, u32, u32)], r: u32) -> bool {
    let i = table.partition_point(|rg| rg.1 < r);
    table
        .get(i)
        .is_some_and(|&(lo, _, stride)| lo <= r && (r - lo) % stride == 0)
}

/// `unicode.IsLetter`.
pub(crate) fn is_letter(r: u32) -> bool {
    is_in(LETTER, r)
}

/// `unicode.IsDigit`.
pub(crate) fn is_digit(r: u32) -> bool {
    if r <= 0xFF {
        return (u32::from(b'0')..=u32::from(b'9')).contains(&r);
    }
    is_in(DIGIT, r)
}

/// `unicode.IsSpace`.
pub(crate) fn is_space(r: u32) -> bool {
    if r <= 0xFF {
        return matches!(r, 0x09..=0x0D | 0x20 | 0x85 | 0xA0);
    }
    is_in(WHITE_SPACE, r)
}

